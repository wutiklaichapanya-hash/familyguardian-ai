// Core domain enums shared by API, web and AI packages. CONTRACT — change only with lead approval.

export const ROLES = ['senior', 'family', 'caregiver', 'admin', 'org_admin'] as const;
export type Role = (typeof ROLES)[number];

/** Data categories a senior can share. Grants are per (grantee × category). */
export const SHARE_CATEGORIES = [
  'checkins',        // daily well-being check-ins (note only if marked shareable)
  'help_requests',   // "Request Help" alerts
  'scam_checks',     // ScamShield assessments the senior chose to share
  'transfer_pauses', // Guardian Pause sessions the senior chose to share
  'care_tasks',      // reminders & care tasks (P1)
  'contacts',        // trusted contact list
] as const;
export type ShareCategory = (typeof SHARE_CATEGORIES)[number];

/** Caregivers may NEVER hold these categories (enforced server-side). */
export const CAREGIVER_FORBIDDEN: readonly ShareCategory[] = ['scam_checks', 'transfer_pauses'];

export const MOODS = ['happy', 'okay', 'lonely', 'worried', 'tired', 'prefer_not_to_answer'] as const;
export type Mood = (typeof MOODS)[number];

/** ScamShield risk categories. There is deliberately NO "safe" category. */
export const RISK_LEVELS = ['low_signals', 'caution', 'high_risk', 'cannot_assess'] as const;
export type RiskLevel = (typeof RISK_LEVELS)[number];

export const SCAM_SIGNALS = [
  'impersonation', 'urgency', 'secrecy', 'credential_request', 'otp_request',
  'suspicious_link', 'lookalike_domain', 'link_shortener', 'advance_fee',
  'investment_promise', 'payment_request', 'remote_access_app', 'threat_or_fear',
  'prize_or_lottery', 'romance', 'unknown_number_pattern',
] as const;
export type ScamSignal = (typeof SCAM_SIGNALS)[number];

export const DASHBOARD_STATUS = [
  'no_action_needed', 'check_in_recommended', 'assistance_requested', 'verify_possible_scam',
] as const;
export type DashboardStatus = (typeof DASHBOARD_STATUS)[number];

export const ALERT_KINDS = ['user_requested_help', 'shared_scam_check', 'shared_transfer_pause', 'shared_checkin_concern'] as const;
export type AlertKind = (typeof ALERT_KINDS)[number];
/** system_warning = generated by app rules; user_requested = senior pressed Help. No "verified_emergency" exists. */
export type AlertOrigin = 'system_warning' | 'user_requested';

export const NOTIFICATION_STATES = ['queued', 'sent', 'failed', 'seen', 'acknowledged', 'cancelled_no_consent'] as const;
export type NotificationState = (typeof NOTIFICATION_STATES)[number];

export const NOTIFICATION_CHANNELS = ['in_app', 'push_simulated', 'email_simulated'] as const;
export type NotificationChannel = (typeof NOTIFICATION_CHANNELS)[number];

/** Action log vocabulary — describes ONLY what the system did. */
export const ACTION_LOG_KINDS = ['call_started_from_app', 'help_request_sent', 'alert_acknowledged'] as const;
export type ActionLogKind = (typeof ACTION_LOG_KINDS)[number];

export type DirectoryVerification = 'verified' | 'needs_human_verification';
