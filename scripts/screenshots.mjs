// Captures real-app screenshots (synthetic demo data) for the ENT501 deck.
import { chromium } from '@playwright/test';
const BASE = process.env.BASE ?? 'http://localhost:3100';
const OUT = process.argv[2] ?? 'docs/presentation/images';
const H = { 'x-fg-csrf': '1', 'content-type': 'application/json' };
const browser = await chromium.launch();
const mk = async () => browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, locale: 'th-TH', colorScheme: 'light' });
const login = async (ctx, email, password) => {
  const r = await ctx.request.post(`${BASE}/api/v1/auth/login`, { headers: H, data: { email, password } });
  if (!r.ok()) throw new Error(`login ${email} ${r.status()}`);
};
const senior = await mk(); await login(senior, 'somsri@demo.fg', 'Demo-Senior-2026');
const p = await senior.newPage();
const hideDev = (pg) => pg.addStyleTag({ content: 'nextjs-portal{display:none!important}' });
await p.goto(`${BASE}/home`); await p.waitForLoadState('networkidle'); await hideDev(p);
await p.screenshot({ path: `${OUT}/app_senior_home.png` });
await p.goto(`${BASE}/scam-check`); await p.waitForLoadState('networkidle'); await hideDev(p);
await p.fill('#scam-text', 'ธนาคารแจ้ง: บัญชีของท่านจะถูกระงับภายใน 24 ชม. กรุณายืนยันตัวตนด่วนที่ hxxp://kbank-secure[.]xyz และแจ้งรหัส OTP ที่ได้รับ ห้ามบอกผู้อื่น');
await p.click('button[type="submit"]');
await p.waitForSelector('#result-h', { timeout: 15000 }); await p.waitForTimeout(500);
await p.locator('#result-h').scrollIntoViewIfNeeded();
await p.evaluate(() => document.querySelector('#result-h')?.scrollIntoView({ block: 'start' }));
await p.screenshot({ path: `${OUT}/app_scamshield_result.png` });
await p.goto(`${BASE}/help`); await p.waitForLoadState('networkidle'); await hideDev(p);
await p.click('button.btn-primary.btn-block');
await p.waitForSelector('#help-status-h', { timeout: 15000 });
const nok = await mk(); await login(nok, 'nok@demo.fg', 'Demo-Family-2026');
await p.waitForTimeout(6000);
const alerts = await (await nok.request.get(`${BASE}/api/v1/alerts`)).json();
const help = alerts.find((a) => a.kind === 'user_requested_help' && !a.acknowledgedBy);
if (!help) throw new Error('no unacked help alert for Nok');
const ack = await nok.request.post(`${BASE}/api/v1/alerts/${help.id}/ack`, { headers: H, data: {} });
if (!ack.ok()) throw new Error(`ack ${ack.status()}`);
await p.waitForTimeout(7000); await hideDev(p);
await p.evaluate(() => document.querySelector('#help-status-h')?.scrollIntoView({ block: 'start' }));
await p.screenshot({ path: `${OUT}/app_help_acknowledged.png` });
const np = await nok.newPage();
await np.goto(`${BASE}/family`); await np.waitForLoadState('networkidle'); await hideDev(np);
await np.screenshot({ path: `${OUT}/app_family_dashboard.png` });
await browser.close();
console.log('saved 4 screenshots to', OUT);
